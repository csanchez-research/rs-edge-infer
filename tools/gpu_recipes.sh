#!/usr/bin/env bash
# =============================================================================
#  gpu_recipes.sh  -  candidate (GPU OpenCL runtime x OpenVINO) combos to probe
# -----------------------------------------------------------------------------
#  Sourced by `deploy.sh gpu-probe`. Each candidate is a pair:
#    GPU_RECIPES[name]    = shell that installs a GPU OpenCL runtime (NEO) in the
#                           probe image (tools/Dockerfile.gpu-probe), and
#    GPU_RECIPE_OV[name]  = the OpenVINO version built in that same image.
#  The kernel that fails (ViT LayerNorm/MVN) is GENERATED BY OPENVINO and
#  COMPILED BY the NEO runtime, so both versions matter and are swept together.
#
#  Order policy: NEWEST FIRST, then fall back to older/legacy. If a newer runtime
#  works it has more useful life, so we try it first and only drop to legacy if it
#  does not. The first PASS wins.
#
#  Hardware reality (Jasper Lake = Gen11, from Intel docs + research + the probe):
#   - Stock Ubuntu 24.04 ships NEO 23.43 -> exposes only OpenCL C 1.2, cannot
#     compile the work_group kernel (ubuntu-stock FAILed).
#   - Mainline NEO (e.g. 26.31.39395.13) DROPPED Gen11: Intel moves Gen8-11 to a
#     legacy track (LEGACY_PLATFORMS.md), so a new mainline NEO sees no GPU at all
#     (matches the earlier kobuk NO_GPU). We still probe the newest first, to test
#     and record it.
#   - Intel's LEGACY release for Gen8-11 is 24.35.30872.36: the newest runtime
#     that still supports Gen11. Best working outcome = legacy + OpenVINO 2025.4
#     (newest, longest life); legacy + 2025.3 is the cleanest (2025.3 is already
#     CPU-validated on the N5105, so only the GPU runtime would change). Note AVX2
#     is required only from OpenVINO 2026.0+, so 2025.4 is also CPU-safe here.
#
#  EDIT freely. Exact .deb sets + versions below come from the Intel release pages.
# =============================================================================

# --- NEO install snippets (run as root inside the probe image) ---------------
_NEO_STOCK="apt-get update && apt-get install -y --no-install-recommends intel-opencl-icd && rm -rf /var/lib/apt/lists/*"

# OpenCL-only sets (ICD + IGC + gmmlib); the Level-Zero package is left out (not
# needed for the OpenCL path that fails, and it avoids an extra loader dependency).
# curl takes multiple -O (no loop, no quoting); dpkg then apt -f resolves deps.

# Newest mainline compute-runtime 26.31.39395.13 + IGC v2.40.13 (Gen12+ per Intel;
# probed first to test/record whether it enumerates Gen11 at all).
_IGC_NEW="https://github.com/intel/intel-graphics-compiler/releases/download/v2.40.13"
_CR_NEW="https://github.com/intel/compute-runtime/releases/download/26.31.39395.13"
_NEO_NEWEST="mkdir -p /tmp/neo && cd /tmp/neo && apt-get update && curl -fsSL -O ${_IGC_NEW}/intel-igc-core-2_2.40.13+22418_amd64.deb -O ${_IGC_NEW}/intel-igc-opencl-2_2.40.13+22418_amd64.deb -O ${_CR_NEW}/libigdgmm12_22.10.0_amd64.deb -O ${_CR_NEW}/intel-opencl-icd_26.31.39395.13-0_amd64.deb && (dpkg -i *.deb || apt-get install -f -y) && cd / && rm -rf /tmp/neo /var/lib/apt/lists/*"

# Legacy compute-runtime 24.35.30872.36 + IGC 1.0.17537.24 (Gen8-11; the newest
# runtime that still supports Jasper Lake).
_IGC_LEG="https://github.com/intel/intel-graphics-compiler/releases/download/igc-1.0.17537.24"
_CR_LEG="https://github.com/intel/compute-runtime/releases/download/24.35.30872.36"
_NEO_LEGACY="mkdir -p /tmp/neo && cd /tmp/neo && apt-get update && curl -fsSL -O ${_IGC_LEG}/intel-igc-core_1.0.17537.24_amd64.deb -O ${_IGC_LEG}/intel-igc-opencl_1.0.17537.24_amd64.deb -O ${_CR_LEG}/libigdgmm12_22.5.0_amd64.deb -O ${_CR_LEG}/intel-opencl-icd-legacy1_24.35.30872.36_amd64.deb && (dpkg -i *.deb || apt-get install -f -y) && cd / && rm -rf /tmp/neo /var/lib/apt/lists/*"

# --- candidates: name -> (NEO install, OpenVINO version) ---------------------
declare -A GPU_RECIPES=(
  [newest26.31-ov2025.4]="$_NEO_NEWEST"
  [legacy24.35-ov2025.4]="$_NEO_LEGACY"
  [legacy24.35-ov2025.3]="$_NEO_LEGACY"
  [stock-ov2025.4]="$_NEO_STOCK"
  [stock-ov2025.3]="$_NEO_STOCK"
  [stock-ov2025.1]="$_NEO_STOCK"
  [stock-ov2024.6]="$_NEO_STOCK"
)
declare -A GPU_RECIPE_OV=(
  [newest26.31-ov2025.4]="2025.4.0"
  [legacy24.35-ov2025.4]="2025.4.0"
  [legacy24.35-ov2025.3]="2025.3.0"
  [stock-ov2025.4]="2025.4.0"
  [stock-ov2025.3]="2025.3.0"
  [stock-ov2025.1]="2025.1.0"
  [stock-ov2024.6]="2024.6.0"
)

# ORDER = what this run probes. The 5-way (NEO x OpenVINO 2025.3/2025.4) sweep is
# DONE and conclusive (all FAIL / NO_GPU; see state/gpu_runtime_probe.json and the
# decisions note). This round tests the last lever: OLDER OpenVINO (stock NEO, which
# enumerates Gen11), in case an older build emitted a 1.2-compatible MVN kernel.
# To re-run the full matrix, list all names here instead.
GPU_RECIPE_ORDER=(stock-ov2025.1 stock-ov2024.6)